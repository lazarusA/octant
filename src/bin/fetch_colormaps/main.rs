//! # fetch_colormaps
//!
//! A one-shot data preparation tool that reads every bundled colormap from its
//! original project (Matplotlib, BIDS, cmocean, Crameri's Zenodo archive,
//! colorcet, CMasher, ColorBrewer, Paul Tol, CARTOColors, Moreland, ...), each
//! pinned in `families/urls.rs`, and writes them as a compact binary catalog
//! (`assets/colormaps/colormaps.bin`) together with the upstream license texts
//! and attribution notices (`assets/colormaps/LICENSES.md`). Families whose
//! license is not compatible with `MIT OR Apache-2.0` are refused. The one
//! deliberate exception to "original project only" is the Paintings family,
//! whose palettes were created by the ColorSchemes.jl authors themselves.

#[cfg(target_arch = "wasm32")]
fn main() {}

#[cfg(not(target_arch = "wasm32"))]
fn main() {
    desktop::run();
}

#[cfg(not(target_arch = "wasm32"))]
mod classify;
#[cfg(not(target_arch = "wasm32"))]
mod families;
#[cfg(not(target_arch = "wasm32"))]
mod fetch;
#[cfg(not(target_arch = "wasm32"))]
mod sources;

#[cfg(not(target_arch = "wasm32"))]
mod desktop {
    use super::families::{self, Family};
    use super::fetch::{Error, Fetcher};
    use octant::utils::colormap::format::{self, CatalogRecords, FamilyRecord};
    use std::{fmt::Write as _, fs, path::Path};

    pub fn run() {
        if let Err(e) = try_run() {
            eprintln!("ERROR: {e}");
            std::process::exit(1);
        }
    }

    fn try_run() -> Result<(), Error> {
        for family in families::all() {
            families::check_compatible(family)?;
        }
        let out_dir = Path::new("assets/colormaps");
        fs::create_dir_all(out_dir)?;

        let mut fetcher = Fetcher::new()?;
        let mut records = CatalogRecords::default();
        let mut licenses = licenses_header();
        for (idx, family) in families::all().enumerate() {
            let maps = fetcher.family_maps(family, u8::try_from(idx)?)?;
            println!(
                "{:<22} {:>4} maps  ({})",
                family.name,
                maps.len(),
                family.license_id
            );
            let text = fetcher.license_text(family)?;
            append_license(&mut licenses, family, maps.len(), &text)?;
            records.families.push(FamilyRecord {
                key: family.key.into(),
                name: family.name.into(),
                license: family.license_id.into(),
                source: family.source.into(),
                attribution: family.attribution.into(),
            });
            records.maps.extend(maps);
        }

        let bytes = format::encode(&records)?;
        fs::write(out_dir.join("colormaps.bin"), &bytes)?;
        fs::write(out_dir.join("LICENSES.md"), licenses)?;
        println!(
            "Wrote {} colormaps ({:.1} KB) to {}",
            records.maps.len(),
            bytes.len() as f32 / 1024.0,
            out_dir.display()
        );
        Ok(())
    }

    fn licenses_header() -> String {
        "# Bundled colormap licenses\n\n\
         Generated by `cargo run --bin fetch_colormaps` from the original projects \
         listed per family (pinned in `src/bin/fetch_colormaps/families/urls.rs`). \
         Each family keeps the license of its original authors.\n\n\
         Changes made by Octant to every colormap: color values are quantized to 8-bit \
         sRGB and resampled into 256-entry lookup tables for display; maps defined by \
         Matplotlib segment data or functions are sampled at 256 points as Matplotlib \
         does. No other changes are made.\n"
            .to_string()
    }

    fn append_license(
        out: &mut String,
        family: &Family,
        count: usize,
        text: &str,
    ) -> Result<(), Error> {
        write!(
            out,
            "\n## {} ({count} maps)\n\n- License: {}\n- Source: {}\n- Attribution: {}\n\n```text\n{}\n```\n",
            family.name,
            family.license_id,
            family.source,
            family.attribution,
            text.trim_end()
        )?;
        Ok(())
    }
}
